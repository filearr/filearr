func TestModel3DWatertightFalseWithAFaceRemoved(t *testing.T) {
	open := cubeTris()[:11] // drop one triangle: four edges now belong to one face
	m := runModel3D(t, "open.stl", binarySTL(t, open, "solid open"))
	wantKey(t, m, "triangles", 11)
	wantKey(t, m, "watertight", false)
}

func TestModel3DUnsupportedExtension(t *testing.T) {
	// model3d.py:89-91 returns {"unsupported": True} for anything outside
	// _GEOMETRY_EXTS. It is a fact about the format, never an error.
	res := &Result{Meta: map[string]any{}}
	p := writeFile(t, t.TempDir(), "drawing.dwg", []byte("not really a dwg"))
	if err := extractModel3D(context.Background(), p, "dwg", Options{}, res); err != nil {
		t.Fatalf("unsupported extension must not error: %v", err)
	}
	wantKey(t, res.Meta, "unsupported", true)
	if len(res.Meta) != 1 {
		t.Fatalf("unsupported result should carry nothing else: %#v", res.Meta)
	}
}

func TestModel3DSizeGuard(t *testing.T) {
	orig := model3dMaxBytes
	t.Cleanup(func() { model3dMaxBytes = orig })
	model3dMaxBytes = 64 // lowered so the guard is testable without a 512 MiB file

	err := runModel3DErr(t, "cube.stl", binarySTL(t, cubeTris(), "solid"))
	if err == nil {
		t.Fatal("expected the size guard to fire")
	}
	if !strings.Contains(err.Error(), "guard") {
		t.Fatalf("guard failures must say so (operators triage on it): %v", err)
	}
}

func TestModel3DRejectsGarbage(t *testing.T) {
	cases := map[string][]byte{
		"cube.stl":  []byte("this is not an STL at all\n"),
		"cube.ply":  []byte("plywood\n"),
		"cube.gltf": []byte("{not json"),
		"cube.glb":  []byte("NOPE\x02\x00\x00\x00"),
		"cube.3mf":  []byte("PK-not-a-zip"),
	}
	for name, data := range cases {
		if err := runModel3DErr(t, name, data); err == nil {
			t.Fatalf("%s: expected an error for garbage input", name)
		}
	}
}

func TestModel3DHonorsCancellation(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	p := writeFile(t, t.TempDir(), "cube.stl", binarySTL(t, cubeTris(), "solid"))
	res := &Result{Meta: map[string]any{}}
	if err := extractModel3D(ctx, p, "stl", Options{}, res); err == nil {
		t.Fatal("expected a cancelled context to abort the parse")
	}
}
