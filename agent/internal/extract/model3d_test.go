func TestModel3DOFF(t *testing.T) {
	m := runModel3D(t, "cube.off", offCube())
	wantGeometry(t, m, "off", 12, 8, 1, [3]float64{1, 1, 1}, 1)
	wantKey(t, m, "watertight", true)
}

func TestModel3DOFFRejectsUnknownVariant(t *testing.T) {
	// 4OFF's vertices are homogeneous 4-D coordinates; parsing them as x y z
	// would be silently wrong, so the variant is rejected explicitly.
	if err := runModel3DErr(t, "cube.off", []byte("4OFF\n1 0 0\n0 0 0 1\n")); err == nil {
		t.Fatal("expected 4OFF to be rejected")
	}
	if err := runModel3DErr(t, "cube.off", []byte("OFF BINARY\n")); err == nil {
		t.Fatal("expected binary OFF to be rejected")
	}
}

func TestModel3DGLTF(t *testing.T) {
	m := runModel3D(t, "cube.gltf", []byte(gltfCube))
	// triangles from the index accessor (36/3); bbox from the POSITION accessor's
	// mandatory min/max — no buffer is decoded.
	wantGeometry(t, m, "gltf", 12, 8, 1, [3]float64{1, 1, 1}, 1)
	wantAbsent(t, m, "watertight") // topology was never read, so it is not claimed
}

func TestModel3DGLB(t *testing.T) {
	m := runModel3D(t, "cube.glb", glbOf(t, gltfCube))
	wantGeometry(t, m, "glb", 12, 8, 1, [3]float64{1, 1, 1}, 1)
	wantAbsent(t, m, "watertight")
}

func TestModel3DGLTFUnindexedPrimitive(t *testing.T) {
	doc := `{"meshes":[{"primitives":[{"attributes":{"POSITION":0}}]}],
	         "accessors":[{"count":36,"min":[0,0,0],"max":[2,2,2]}]}`
	m := runModel3D(t, "soup.gltf", []byte(doc))
	// No index accessor: triangles fall back to POSITION count / 3.
	wantGeometry(t, m, "gltf", 12, 36, 1, [3]float64{2, 2, 2}, 8)
}

